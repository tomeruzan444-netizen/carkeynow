/**
 * @param slug  מזהה העמוד
 * @param used  כתובות תמונות שכבר מוטמעות בגוף העמוד. הן לא ייכנסו לגלריה
 *              כדי שאותה תמונה לא תופיע פעמיים באותו עמוד.
 */
export function getGallery(slug: string, used?: ReadonlySet<string>): Gallery | null {
  /* שכפול מפתח לרכב לפי עיר */
  if (slug.startsWith('שכפול-מפתח-לרכב-ב')) {
    const city = cityFrom(slug, 'שכפול-מפתח-לרכב-ב');
    const kw = `שכפול מפתח לרכב ב${city}`;
    return gallery(
      `${kw} - תמונות מהשטח`,
      'מפתחות קפיץ, שלטים חכמים וקידוד שמתבצע בעמדה ניידת ליד הרכב',
      pick(KEY_SET, KEY_RESERVE, 6, used), kw,
    );
  }

  if (slug === 'שכפול-מפתח-לרכב') {
    return gallery(
      'שכפול מפתח לרכב - תמונות מהעבודה שלנו',
      'מגלם חדש ועד מפתח מקודד שמתניע את הרכב',
      pick(KEY_SET, KEY_RESERVE, 6, used), 'שכפול מפתח לרכב',
    );
  }

  /* עמודי יצרן - רק ליצרנים שיש להם תמונת מפתח משלהם.
     אם התמונה היחידה של היצרן כבר מוטמעת בגוף העמוד, אין גלריה:
     גלריה של מפתחות גנריים בעמוד יצרן לא תורמת ומטשטשת את הרלוונטיות. */
  const brand = BRAND_GALLERY[slug];
  if (brand) {
    const own = pick(brand.own, [], brand.own.length, used);
    if (own.length === 0) return null;
    const kw = `שכפול מפתח ל${brand.name}`;
    return gallery(
      `מפתחות ושלטים ל${brand.name} שעברו דרכנו`,
      `כל התמונות מעבודות שכפול מפתח ל${brand.name} וקידוד שלטים בשטח`,
      pick(own, NEUTRAL_FILL, Math.max(3, own.length), used), kw,
    );
  }

  /* קודן לרכב */
  if (slug.includes('קודן')) {
    const KODAN_KW: Record<string, string> = {
      'איפוס-קודן-לרכב': 'איפוס קודן לרכב',
      'התקנת-קודן-לרכב': 'התקנת קודן לרכב',
      'ניתוק-קודן-לרכב': 'ניתוק קודן לרכב',
      'תיקון-קודן-לרכב': 'תיקון קודן לרכב',
      'קודן-לרכב-מצפצף-2': 'קודן לרכב מצפצף',
    };
    const isCity = slug.startsWith('קודן-לרכב-ב');
    const kw = isCity
      ? `קודן לרכב ב${cityFrom(slug, 'קודן-לרכב-ב')}`
      : KODAN_KW[slug] || 'קודן לרכב';
    return gallery(
      isCity ? `כך נראה ${kw} במציאות` : 'כך נראה קודן לרכב במציאות',
      'שתי מערכות קודן שטיפלנו בהן, כולל מיקום ההתקנה וסימני הבלאי',
      pick(KODAN_SET, [], 2, used), kw,
    );
  }

  /* סוויץ הצתה */
  if (slug.includes('סוויץ')) {
    const SWITCH_KW: Record<string, string> = {
      'סוויץ-לרכב-בנתניה': 'סוויץ לרכב בנתניה',
      'מפתח-תקוע-בסוויץ': 'מפתח תקוע בסוויץ',
      'תיקון-סוויץ-לרכב': 'תיקון סוויץ לרכב',
    };
    return gallery(
      'סוויץ ההצתה מבפנים',
      'מהמפתח שנתקע ועד המנגנון החשוף אחרי פירוק עמוד ההגה',
      pick(SWITCH_SET, [], 3, used), SWITCH_KW[slug] || 'תיקון סוויץ לרכב',
    );
  }

  /* שלטים */
  const REMOTE_PAGES: Record<string, string> = {
    'קידוד-שלט-לרכב': 'קידוד שלט לרכב',
    'שכפול-שלט-לרכב': 'שכפול שלט לרכב',
    'שלט-לרכב-לא-עובד': 'שלט לרכב לא עובד',
    'תיקון-שלט-לרכב': 'תיקון שלט לרכב',
  };
  if (REMOTE_PAGES[slug]) {
    return gallery(
      'שלטים לרכב שעברו אצלנו קידוד',
      'שלטים חכמים ושלטי קפיץ, לפני ואחרי הסנכרון למחשב הרכב',
      pick(REMOTE_SET, [], 5, used), REMOTE_PAGES[slug],
    );
  }

  /* אובדן ושחזור מפתח */
  if (slug === 'אבד-מפתח-לרכב' || slug === 'שחזור-מפתח-לרכב') {
    const kw = slug === 'אבד-מפתח-לרכב' ? 'אבד מפתח לרכב' : 'שחזור מפתח לרכב';
    return gallery(
      'מפתחות שייצרנו מאפס',
      'כשאין מפתח מקור, מייצרים חדש לפי קוד המנעול ומקודדים אותו במקום',
      pick(LOST_SET, LOST_RESERVE, 5, used), kw,
    );
  }

  /* מחירון */
  if (slug.startsWith('מדד-מחירי')) {
    return gallery(
      'סוגי המפתחות והשלטים שבמחירון',
      'כל סוג מפתח מתומחר אחרת - הנה איך הם נראים בפועל',
      pick(INDEX_SET, INDEX_RESERVE, 4, used), 'מחיר שכפול מפתח לרכב',
    );
  }

  /* אודות ומנעולן רכב */
  if (slug === 'אודות') {
    return gallery(
      'הצוות, הניידת והתעודות שלנו',
      'מי אנחנו ומה יוצא איתנו לכל קריאה',
      pick(TRUST_SET, [], 3, used), 'מפתח עכשיו - מנעולן רכב',
    );
  }
  if (slug === 'מנעולן-רכב-בתל-אביב') {
    return gallery(
      'הצוות והניידת שמגיעים אליכם',
      'מעבדה ניידת מלאה, צוות מורשה ותעודת מנעולן מקצועי',
      pick(TRUST_SET, [], 3, used), 'מנעולן רכב בתל אביב',
    );
  }

  /* כל השאר - פריצת רכב, אופנועים, עמודים משפטיים - אין תמונות רלוונטיות */
  return null;
}
