/* ── בניית פריט גלריה ── */
type Pair = [Shot, string];

function build(pairs: Pair[], keyword: string): GalleryImage[] {
  return pairs.map(([s, caption]) => ({
    src: s.src,
    w: s.w,
    h: s.h,
    caption,
    alt: `${s.desc} - ${keyword}`,
  }));
}

/**
 * בוחר את התמונות שייכנסו לגלריה.
 * תמונה שכבר מופיעה בגוף העמוד (used) מדולגת, כדי שלא תוצג פעמיים.
 * כשמדלגים, משלימים מרשימת המילואים של אותה קבוצה.
 */
function pick(main: Pair[], reserve: Pair[], want: number, used?: ReadonlySet<string>): Pair[] {
  const out: Pair[] = [];
  const seen = new Set<string>();
  for (const p of [...main, ...reserve]) {
    if (out.length >= want) break;
    if (seen.has(p[0].src) || used?.has(p[0].src)) continue;
    seen.add(p[0].src);
    out.push(p);
  }
  return out;
}

/* פחות משתי תמונות זה כבר לא סליידר. במקרה כזה לא מציגים גלריה בכלל. */
const MIN_IMAGES = 2;

function gallery(
  heading: string, sub: string, pairs: Pair[], keyword: string,
): Gallery | null {
  return pairs.length >= MIN_IMAGES
    ? { heading, sub, images: build(pairs, keyword) }
    : null;
}

/* ── שם העיר מתוך ה-slug ── */
const CITY_FIX: Record<string, string> = { 'אש העין': 'ראש העין' };

function cityFrom(slug: string, prefix: string): string {
  const raw = slug.slice(prefix.length).replace(/-/g, ' ').replace(/ 2$/, '');
  return CITY_FIX[raw] || raw;
}

