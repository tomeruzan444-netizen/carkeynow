export const citySlug = (city: string) => CITY_PREFIX + city.replace(/ /g, '-');

/* נקרא בזמן בנייה עם כל הסלאגים באתר */
export function assertCityRegions(allSlugs: string[]) {
  const pages = new Set(allSlugs.filter((s) => s.startsWith(CITY_PREFIX)));
  const inRegions = CITY_REGIONS.flatMap((r) => r.cities);
  const problems: string[] = [];
  for (const s of pages) {
    const c = s.slice(CITY_PREFIX.length).replace(/-/g, ' ');
    if (!inRegions.includes(c)) problems.push(`עמוד בלי אזור: ${c}`);
    if (!CITY_NEIGHBORS[c]) problems.push(`עמוד בלי שכנים: ${c}`);
  }
  for (const c of inRegions) if (!pages.has(citySlug(c))) problems.push(`באזור אבל בלי עמוד: ${c}`);
  for (const [c, ns] of Object.entries(CITY_NEIGHBORS))
    for (const n of ns) if (!pages.has(citySlug(n))) problems.push(`שכן בלי עמוד: ${c} ← ${n}`);
  if (problems.length) throw new Error('cityRegions: ' + problems.join('; '));
}

/* שם העיר מתוך סלאג של עמוד עיר, או null */
export function cityFromSlug(slug: string): string | null {
  if (!slug.startsWith(CITY_PREFIX)) return null;
  const name = slug.slice(CITY_PREFIX.length).replace(/-/g, ' ');
  return name in CITY_NEIGHBORS ? name : null;
}
