import { WP_PAGES } from '@/lib/wp-pages';
import { SITE } from '@/lib/siteData';
import { AUTHOR } from '@/lib/author';

// נוצר סטטית בזמן build ומוגש כ-/llms.txt (מסונכרן אוטומטית עם WP_PAGES)
export const dynamic = 'force-static';

function phraseOf(title: string): string {
  return title
    .split(/\s+[-|]\s+|\?/)[0]
    .replace(/&#8211;/g, '-')
    .replace(/&amp;/g, '&')
    .replace(/&#8217;/g, "'")
    .trim();
}

const U = (slug: string) => `${SITE.url}/${slug}/`;

export function GET() {
  const brands = WP_PAGES.filter(
    (p) => p.slug.startsWith('שכפול-מפתח-ל') && !p.slug.startsWith('שכפול-מפתח-לרכב'),
  );
  const keyCities = WP_PAGES.filter((p) => p.slug.startsWith('שכפול-מפתח-לרכב-ב'));
  const lockout = WP_PAGES.filter((p) => p.slug.startsWith('פורץ-רכבים'));
  const alarm = WP_PAGES.filter((p) => p.slug.startsWith('קודן-לרכב'));

  const list = (arr: typeof WP_PAGES) =>
    arr.map((p) => `- [${phraseOf(p.title)}](${U(p.slug)})`).join('\n');

  const content = `# ${SITE.name} - ${SITE.tagline}

> ${SITE.name} הוא שירות מנעולנות רכב ארצי בישראל, שנוסד על ידי ${AUTHOR.name} (${AUTHOR.jobTitle}). אנחנו מתמחים אך ורק במנעולנות רכב: שכפול מפתחות, שחזור מפתח שאבד, קידוד ותיקון שלט, תיקון סוויץ, פתיחת רכב נעול (פורץ רכבים) והתקנת/ניתוק קודן. השירות ניתן עד הרכב בכל רחבי הארץ, 24 שעות ביממה כולל שבתות וחגים, במחירים שקופים מראש. כל עמוד באתר כולל מחירון בשקלים, זמני הגעה משוערים ודוגמאות אמיתיות מהשטח.

## שירותים עיקריים
- [שכפול מפתח לרכב](${U('שכפול-מפתח-לרכב')}): שכפול מפתח מכני, מפתח שבב או Smart Key לכל דגם רכב, בשטח. טווח מחירים 150-1,500 ₪.
- [שחזור מפתח לרכב](${U('שחזור-מפתח-לרכב')}): ייצור מפתח חדש גם ללא מפתח מקורי, באמצעות שליפת קוד האימוביליזר ממחשב הרכב.
- [אבד מפתח לרכב](${U('אבד-מפתח-לרכב')}): פתרון מיידי לאובדן מפתח - פתיחת הרכב וייצור מפתח חדש בשטח.
- [שכפול שלט לרכב](${U('שכפול-שלט-לרכב')}): שכפול וקידוד שלט רחוק לכל היצרנים.
- [קידוד שלט לרכב](${U('קידוד-שלט-לרכב')}): קידוד וסנכרון שלט למחשב הרכב.
- [תיקון שלט לרכב](${U('תיקון-שלט-לרכב')}): תיקון שלט שאינו פותח, כולל סוללה ואנטנה.
- [תיקון סוויץ לרכב](${U('תיקון-סוויץ-לרכב')}): תיקון והחלפת סוויץ הצתה בשטח, כולל קידוד.
- [מפתח תקוע בסוויץ](${U('מפתח-תקוע-בסוויץ')}): חילוץ מפתח תקוע או שבור מתוך הסוויץ.
- [פורץ רכבים](${U('פורץ-רכבים')}): פתיחת רכב נעול ללא נזק, בשיטות מקצועיות.
- [התקנת קודן לרכב](${U('התקנת-קודן-לרכב')}): התקנת מערכות קודן ואימוביליזר.
- [תיקון קודן לרכב](${U('תיקון-קודן-לרכב')}), [ניתוק קודן לרכב](${U('ניתוק-קודן-לרכב')}): טיפול בקודן תקול או מצפצף.
- [שחזור מפתח לאופנוע](${U('שחזור-מפתח-לאופנוע')}): מפתחות לאופנועים, עם ובלי אימוביליזר.

## שכפול מפתח לפי יצרן רכב
${list(brands)}

## שכפול מפתח לרכב לפי עיר
${list(keyCities)}

## פורץ רכבים לפי עיר
${list(lockout)}

## קודן לרכב לפי עיר ושירות
${list(alarm)}

## מידע על העסק
- [אודות מפתח עכשיו](${U('אודות')}): הסיפור של העסק ושל ${AUTHOR.name}, המייסד והמנעולן המומחה.
- [צרו קשר](${U('צרו-קשר')}): טלפון ${SITE.phoneDisplay}, וואטסאפ וטופס - זמינים 24/7.
`;

  return new Response(content, {
    headers: { 'Content-Type': 'text/plain; charset=utf-8' },
  });
}
